#!/usr/bin/env node
/*
 * build.js — convert cached filter lists (filters/cache/*.txt) into everything
 * the Safari extension needs, and print a budget report.
 *
 * Writes into WebExtension/Resources/:
 *   rules/<id>.json               DNR static ruleset (one per list)
 *   rules/index.json              catalog + per-list counts (read by background/options/host app)
 *   cosmetic/<id>.generic.css     static generic element-hiding CSS
 *   cosmetic/<id>.generic.json    same selectors (for sites excluded from the static CSS)
 *   cosmetic/<id>.specific.json   site-specific cosmetic + scriptlet data (loaded into storage.local)
 *   cosmetic/<id>.exclude.json    hosts that must not get the static generic CSS
 *   scriptlets/<id>.js            MAIN-world scriptlet bundle (generated)
 *   scriptlets/<id>.hosts.json    hosts the bundle is registered for
 *   manifest.json                 declarative_net_request.rule_resources updated in place
 * and, for lists with engine "contentBlocker":
 *   ContentBlockerOverflow1/blockerList.json
 *
 * Usage: node scripts/build.js [--strict]
 */
'use strict';

const fs = require('fs');
const path = require('path');

const LIB = path.resolve(__dirname, '../../WebExtension/Resources/lib');
const FP = require(path.join(LIB, 'filter-parser.js'));
const DNR = require(path.join(LIB, 'dnr-convert.js'));
const CC = require(path.join(LIB, 'cosmetic-compile.js'));
const SR = require(path.join(LIB, 'scriptlet-runner.js'));
const { preprocess } = require('../src/preprocess.js');
const { buildContentBlockerJSON } = require('../src/to-webkit.js');

const ROOT = path.resolve(__dirname, '..');
const RES = path.resolve(ROOT, '../WebExtension/Resources');
const CACHE = path.join(ROOT, 'cache');
const OVERFLOW = path.resolve(ROOT, '../ContentBlockerOverflow1');
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'lists.json'), 'utf8'));
const strict = process.argv.includes('--strict');

const SUPPORTED_SCRIPTLETS = new Set(SR.SUPPORTED);

function stripBadfilter(raw) {
  // canonical form of a filter with the badfilter option removed
  const i = raw.lastIndexOf('$');
  if (i === -1) return raw;
  const opts = raw.slice(i + 1).split(',').filter((o) => o.trim().toLowerCase() !== 'badfilter');
  return opts.length ? raw.slice(0, i + 1) + opts.join(',') : raw.slice(0, i);
}

function writeJSON(file, data, pretty) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(data, null, pretty ? 2 : 0) + (pretty ? '\n' : ''));
}

function cleanDir(dir, re) {
  if (!fs.existsSync(dir)) return;
  for (const f of fs.readdirSync(dir)) if (re.test(f)) fs.unlinkSync(path.join(dir, f));
}

function entityPatterns(key) {
  // "example.*" -> match patterns for common TLDs (match patterns can't wildcard a TLD)
  const base = key.slice(0, -2);
  // Kept short on purpose: every pattern costs matching time in Safari. Pirate/streaming
  // sites that hop TLDs mostly use these.
  const tlds = ['com', 'net', 'org', 'to', 'io', 'cc', 'tv', 'me', 'de', 'co.uk', 'fr', 'it', 'es', 'nl'];
  return tlds.map((t) => `*://*.${base}.${t}/*`);
}

function scriptletBundle(id, data) {
  return `/* GENERATED by filters/scripts/build.js — do not edit. List: ${id} */
(function () {
  'use strict';
  if (window.top !== window && location.protocol === 'about:') return;
  var DATA = ${JSON.stringify(data)};
  var host = location.hostname;
  function hostMatches(h, d) {
    if (d.slice(-2) === '.*') {
      var base = d.slice(0, -2), labels = h.split('.');
      for (var i = 0; i < labels.length; i++) {
        var rest = labels.slice(i).join('.');
        if (rest.indexOf(base + '.') === 0) { var tld = rest.slice(base.length + 1); if (tld && tld.split('.').length <= 2) return true; }
      }
      return false;
    }
    return h === d || h.slice(-(d.length + 1)) === '.' + d;
  }
  var labels = host.split('.'), keys = [];
  for (var i = 0; i < labels.length; i++) {
    var rest = labels.slice(i);
    keys.push(rest.join('.'));
    if (rest.length > 1) keys.push(rest.slice(0, -1).join('.') + '.*');
    if (rest.length > 2) keys.push(rest.slice(0, -2).join('.') + '.*');
  }
  var calls = [], except = {};
  keys.forEach(function (k) { (DATA.except[k] || []).forEach(function (n) { except[n] = 1; }); });
  if (except['*']) return;
  (DATA.generic || []).forEach(function (i) { var c = DATA.calls[i]; if (!except[c[0]]) calls.push(c); });
  keys.forEach(function (k) {
    if (k.slice(-2) === '.*' && !hostMatches(host, k)) return;
    (DATA.hosts[k] || []).forEach(function (t) {
      var c = DATA.calls[t[0]];
      if (except[c[0]]) return;
      if (t[1] && t[1].some(function (x) { return hostMatches(host, x); })) return;
      calls.push(c);
    });
  });
  if (!calls.length) return;
  (${SR.abdScriptletRunner.toString()})(calls);
})();
`;
}

function hashKey(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

function matchesForKey(k) {
  return FP.isEntity(k) ? entityPatterns(k) : [`*://*.${k}/*`];
}

function writeScriptletShards(id, cc, scriptletExcept) {
  const dir = path.join(RES, 'scriptlets');
  fs.mkdirSync(dir, { recursive: true });
  const keys = cc.scriptletHosts;
  const approxBytes = keys.reduce((n, k) => n + JSON.stringify(cc.specific[k].sl).length + k.length, 0);
  const shardCount = Math.max(1, Math.ceil(approxBytes / (120 * 1024)));
  const shards = Array.from({ length: shardCount }, () => []);
  for (const k of keys) shards[hashKey(k) % shardCount].push(k);
  const manifest = [];
  const build = (name, shardKeys, generic) => {
    const calls = [];
    const callIdx = new Map();
    const idxOf = (c) => {
      const key = JSON.stringify([c[0], c[1]]);
      let i = callIdx.get(key);
      if (i === undefined) { i = calls.length; calls.push([c[0], c[1]]); callIdx.set(key, i); }
      return i;
    };
    const hosts = {};
    for (const k of shardKeys) hosts[k] = cc.specific[k].sl.map((c) => (c[2] ? [idxOf(c), c[2]] : [idxOf(c)]));
    const gen = generic.map(idxOf);
    const data = { calls, hosts, generic: gen, except: scriptletExcept };
    fs.writeFileSync(path.join(dir, name + '.js'), scriptletBundle(id, data));
    const matches = generic.length ? ['<all_urls>'] : Array.from(new Set(shardKeys.flatMap(matchesForKey)));
    manifest.push({ file: `scriptlets/${name}.js`, matches });
  };
  if (cc.genericScriptlets.length) build(`${id}.generic`, [], cc.genericScriptlets);
  shards.forEach((shardKeys, i) => { if (shardKeys.length) build(`${id}.${i}`, shardKeys, []); });
  writeJSON(path.join(dir, id + '.index.json'), manifest);
  return manifest;
}

function main() {
  const lists = catalog.lists.slice().sort((a, b) => a.priority - b.priority);

  // ---- pass 1: read + parse everything, collect global badfilters / scriptlet exceptions ----
  const parsedByList = new Map();
  const badfilters = new Set();
  const missing = [];
  for (const l of lists) {
    const file = path.join(CACHE, l.id + '.txt');
    if (!fs.existsSync(file)) { missing.push(l.id); continue; }
    const lines = preprocess(fs.readFileSync(file, 'utf8'));
    const parsed = [];
    for (const line of lines) {
      const f = FP.parseFilter(line);
      if (f.type === 'comment') continue;
      if (f.type === 'network' && f.options.badfilter) { badfilters.add(stripBadfilter(f.raw)); continue; }
      parsed.push(f);
    }
    parsedByList.set(l.id, parsed);
  }
  if (missing.length) {
    console.error('Missing cached lists: ' + missing.join(', ') + '\nRun: node scripts/fetch.js');
    if (missing.length === lists.length) process.exit(1);
  }

  // Global scriptlet exceptions (unbreak lists often disable scriptlets from other lists).
  const scriptletExcept = {};
  for (const parsed of parsedByList.values()) {
    for (const f of parsed) {
      if (f.type !== 'scriptlet' || !f.exception) continue;
      for (const d of f.domains.include) (scriptletExcept[d] || (scriptletExcept[d] = [])).push(f.name || '*');
    }
  }

  cleanDir(path.join(RES, 'rules'), /\.json$/);
  cleanDir(path.join(RES, 'cosmetic'), /\.(json|css)$/);
  cleanDir(path.join(RES, 'scriptlets'), /\.(js|json)$/);

  const index = [];
  const overflowRules = [];
  const report = [];

  for (const l of lists) {
    const parsed = parsedByList.get(l.id);
    if (!parsed) continue;
    const skipReasons = {};
    const rules = [];
    const metas = [];
    const cosmetic = [];
    let unsupported = 0;
    for (const f of parsed) {
      if (f.type === 'unsupported') { unsupported++; skipReasons[f.reason] = (skipReasons[f.reason] || 0) + 1; continue; }
      if (badfilters.has(f.raw)) continue;
      if (f.type === 'network') {
        const r = DNR.convertNetworkFilter(f);
        if (r.skip) { skipReasons[r.skip.replace(/:.*/, '')] = (skipReasons[r.skip.replace(/:.*/, '')] || 0) + 1; }
        if (r.meta) metas.push(r.meta);
        rules.push(...r.rules);
      } else {
        cosmetic.push(f);
      }
    }

    const merged = DNR.mergeRules(rules);
    // Most specific / important first in the file (helps when trimming).
    merged.sort((a, b) => b.priority - a.priority);
    let cost = merged.reduce((n, r) => n + DNR.webkitCost(r), 0);
    DNR.assignIds(merged, 1);

    const cc = CC.compileCosmetic(cosmetic, metas, { supportedScriptlets: SUPPORTED_SCRIPTLETS });

    if (l.engine === 'contentBlocker') {
      overflowRules.push(...merged);
    } else {
      writeJSON(path.join(RES, 'rules', l.id + '.json'), merged);
    }

    // cosmetic outputs
    fs.mkdirSync(path.join(RES, 'cosmetic'), { recursive: true });
    fs.writeFileSync(path.join(RES, 'cosmetic', l.id + '.generic.css'), CC.buildHideCSS(cc.genericHide));
    writeJSON(path.join(RES, 'cosmetic', l.id + '.generic.json'), cc.genericHide);
    writeJSON(path.join(RES, 'cosmetic', l.id + '.specific.json'), cc.specific);
    writeJSON(path.join(RES, 'cosmetic', l.id + '.exclude.json'), cc.genericExcludeHosts);

    // scriptlets — deduped call table, sharded by host so each page only loads
    // a small bundle (~<=150 KB) instead of the whole list's data.
    let scriptletShards = [];
    if (cc.scriptletHosts.length || cc.genericScriptlets.length) {
      scriptletShards = writeScriptletShards(l.id, cc, scriptletExcept);
    }

    const info = {
      id: l.id, name: l.name, group: l.group, engine: l.engine, defaultEnabled: l.defaultEnabled, priority: l.priority,
      url: l.url,
      dnrRules: merged.length, webkitCost: cost,
      genericSelectors: cc.genericHide.length,
      specificHosts: Object.keys(cc.specific).length,
      excludeHosts: cc.genericExcludeHosts.length,
      scriptletHosts: cc.scriptletHosts.length,
      scriptletShards: scriptletShards.length,
      hasScriptlets: scriptletShards.length > 0,
      unsupported,
      builtAt: new Date().toISOString(),
    };
    index.push(info);
    report.push({ info, cc, skipReasons });
  }

  writeJSON(path.join(RES, 'rules', 'index.json'), { builtAt: new Date().toISOString(), budget: catalog.budget, lists: index }, true);

  // ---- manifest rule_resources ----
  const manifestFile = path.join(RES, 'manifest.json');
  if (fs.existsSync(manifestFile)) {
    const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
    manifest.declarative_net_request = {
      rule_resources: index.filter((i) => i.engine === 'dnr').map((i) => ({ id: i.id, enabled: !!i.defaultEnabled, path: `rules/${i.id}.json` })),
    };
    fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
  }

  // ---- overflow content blocker ----
  if (overflowRules.length) {
    const json = buildContentBlockerJSON(overflowRules);
    if (json.length > catalog.budget.contentBlockerRules) {
      console.warn(`! overflow content blocker has ${json.length} rules; trimming to ${catalog.budget.contentBlockerRules}`);
      json.length = catalog.budget.contentBlockerRules;
    }
    writeJSON(path.join(OVERFLOW, 'blockerList.json'), json);
  } else if (fs.existsSync(OVERFLOW)) {
    // Keep a valid (tiny) list so the optional target still builds.
    writeJSON(path.join(OVERFLOW, 'blockerList.json'), [{ trigger: { 'url-filter': '^abd-overflow-placeholder:' }, action: { type: 'block' } }]);
  }

  // ---- report ----
  const pad = (s, n) => String(s).padEnd(n);
  const lpad = (s, n) => String(s).padStart(n);
  console.log('\n' + pad('list', 20) + lpad('dnr', 8) + lpad('webkit', 9) + lpad('generic', 9) + lpad('hosts', 8) + lpad('scrlt', 7) + lpad('unsup', 7) + '  on');
  let enabledCost = 0;
  let allCost = 0;
  for (const { info } of report) {
    if (info.engine === 'dnr') { allCost += info.webkitCost; if (info.defaultEnabled) enabledCost += info.webkitCost; }
    console.log(pad(info.id, 20) + lpad(info.dnrRules, 8) + lpad(info.webkitCost, 9) + lpad(info.genericSelectors, 9) +
      lpad(info.specificHosts, 8) + lpad(info.scriptletHosts, 7) + lpad(info.unsupported, 7) + '  ' + (info.engine === 'dnr' ? (info.defaultEnabled ? 'yes' : 'no') : 'CB'));
  }
  const budget = catalog.budget.dnrWebKitRules;
  console.log(`\nDNR WebKit cost of default-enabled lists: ${enabledCost} / budget ${budget} (hard Safari cap 150000 incl. dynamic rules)`);
  console.log(`DNR WebKit cost if ALL dnr lists enabled: ${allCost}`);
  const topSkips = {};
  for (const { skipReasons } of report) for (const [k, v] of Object.entries(skipReasons)) topSkips[k] = (topSkips[k] || 0) + v;
  console.log('Top skip reasons: ' + Object.entries(topSkips).sort((a, b) => b[1] - a[1]).slice(0, 12).map(([k, v]) => `${k}=${v}`).join(', '));
  const dropped = {};
  for (const { cc } of report) for (const [k, v] of Object.entries(cc.droppedScriptletNames)) dropped[k] = (dropped[k] || 0) + v;
  console.log('Unsupported scriptlets (top): ' + Object.entries(dropped).sort((a, b) => b[1] - a[1]).slice(0, 12).map(([k, v]) => `${k}=${v}`).join(', '));

  if (enabledCost > budget) {
    console.error(`\n✗ Default-enabled lists exceed the DNR budget by ${enabledCost - budget}. Disable a list by default, move it to engine "contentBlocker", or raise the budget carefully.`);
    if (strict) process.exit(2);
  }
}

main();
